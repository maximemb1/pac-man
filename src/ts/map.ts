let animation_ligne:number = 0;
let conteur_frame:number = 0;
export const met_0_anim_ligne = () => {animation_ligne = 0; conteur_frame = 0};

export function draw_map(map: number[][]){
    if (animation_ligne < map.length) {
        conteur_frame++;
        if (conteur_frame % 5 === 0) animation_ligne++;
    }

    for (let i=0; i < animation_ligne; i++){
        for (let j=0; j < map[i].length; j++){
            if (map[i][j] === 1){
                ctx.fillStyle = "rgb(38, 73, 255)";
                ctx.fillRect(j*TAILLE_CASE, i*TAILLE_CASE, TAILLE_CASE, TAILLE_CASE);
            }
            if (map[i][j] === 2){
                ctx.fillStyle = "rgb(76, 127, 238)";
                ctx.fillRect(j*TAILLE_CASE, i*TAILLE_CASE, TAILLE_CASE, TAILLE_CASE);
            }
        }
    }
    ctx.strokeStyle = "rgba(255,255,255,0.2)";
    ctx.lineWidth = 1;

    for (let i = 0; i <= map.length; i++) {
        ctx.beginPath();
        ctx.moveTo(i * TAILLE_CASE, 0);
        ctx.lineTo(i * TAILLE_CASE, cvs.height);
        ctx.stroke();

        ctx.beginPath();
        ctx.moveTo(0, i * TAILLE_CASE);
        ctx.lineTo(cvs.width, i * TAILLE_CASE);
        ctx.stroke();
    }
}

